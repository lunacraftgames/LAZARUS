// 当前周目角色、当前语言的文本。story = true：开场 / 结局剧情、芯片档案（只做整句改写）
// 英文：整句改写的结果再查英文词典；其余先翻译，再做英文的称呼替换（subsEn）
function charText(s, story) {
  if (typeof s !== 'string') return s;
  const T = CHAR_TEXT[typeof Game !== 'undefined' && Game.charId];
  if (I18N.en) {
    if (T && Object.prototype.hasOwnProperty.call(T.lines, s)) return tr(T.lines[s]);
    let out = tr(s);
    if (T && !story && T.subsEn) {
      const KEEP = '\u0001';
      const toks = [];
      out = out.split('Lazarus Protocol').join(KEEP).replace(/\{[a-z]+\}/g, (m) => { toks.push(m); return '\u0002'; }); // 按键记号 {dash} 等不参与替换
      for (const [a, b] of T.subsEn) out = out.split(a).join(b);
      out = out.split(KEEP).join('Lazarus Protocol').replace(/\u0002/g, () => toks.shift());
    }
    return out;
  }
  if (!T) return s;
  if (Object.prototype.hasOwnProperty.call(T.lines, s)) return T.lines[s];
  if (story) return s;
  const KEEP = '\u0001';
  let out = s.split('拉撒路协议').join(KEEP);
  for (const [a, b] of T.subs) out = out.split(a).join(b);
  return out.split(KEEP).join('拉撒路协议');
}
